/* Build the self-contained ESP32 web UI when Node.js is available. */
const fs = require('fs');
const path = require('path');

const webDir = __dirname;
const output = path.resolve(webDir, '..', 'firmware', 'arduino', 'led_display', 'web_ui.h');
let html = fs.readFileSync(path.join(webDir, 'index.html'), 'utf8');
const css = fs.readFileSync(path.join(webDir, 'style.css'), 'utf8');
const js = fs.readFileSync(path.join(webDir, 'app.js'), 'utf8');

html = html.replace('<link rel="stylesheet" href="style.css">', `<style>\n${css}\n</style>`);
html = html.replace('<script src="app.js"></script>', `<script>\n${js}\n</script>`);

const header = `#ifndef TINKERSPACE_WEB_UI_H
#define TINKERSPACE_WEB_UI_H

#include <Arduino.h>

// Auto-generated by webapp/build_web_ui.py or build_web_ui.js
const char WEB_UI_HTML[] PROGMEM = R"rawliteral(${html})rawliteral";

#endif // TINKERSPACE_WEB_UI_H
`;

fs.writeFileSync(output, header, 'utf8');
console.log(`Bundled web UI into ${output}`);
