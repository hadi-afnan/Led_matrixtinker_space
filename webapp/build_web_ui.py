#!/usr/bin/env python3
"""
TinkerSpace Web UI Bundler
Inlines index.html, style.css, and app.js into a single PROGMEM header
for compilation into the ESP32-S3 firmware.
"""

import os
import re

WEBAPP_DIR = os.path.dirname(os.path.abspath(__file__))
OUTPUT_HEADER = os.path.abspath(os.path.join(WEBAPP_DIR, '..', 'firmware', 'arduino', 'led_display', 'web_ui.h'))

def bundle_web_ui():
    html_path = os.path.join(WEBAPP_DIR, 'index.html')
    css_path = os.path.join(WEBAPP_DIR, 'style.css')
    js_path = os.path.join(WEBAPP_DIR, 'app.js')

    with open(html_path, 'r', encoding='utf-8') as f:
        html = f.read()

    with open(css_path, 'r', encoding='utf-8') as f:
        css = f.read()

    with open(js_path, 'r', encoding='utf-8') as f:
        js = f.read()

    # Inline CSS
    css_tag = f"<style>\n{css}\n</style>"
    html = re.sub(r'<link rel="stylesheet" href="style\.css">', lambda m: css_tag, html)

    # Inline JS
    js_tag = f"<script>\n{js}\n</script>"
    html = re.sub(r'<script src="app\.js"></script>', lambda m: js_tag, html)

    # Format into C++ header with PROGMEM raw literal
    header_content = f'''#ifndef TINKERSPACE_WEB_UI_H
#define TINKERSPACE_WEB_UI_H

#include <Arduino.h>

// Auto-generated by webapp/build_web_ui.py
// Self-contained, responsive single-page web application for TinkerSpace 50x30 LED display

const char WEB_UI_HTML[] PROGMEM = R"rawliteral({html})rawliteral";

#endif // TINKERSPACE_WEB_UI_H
'''

    with open(OUTPUT_HEADER, 'w', encoding='utf-8') as f:
        f.write(header_content)

    size_kb = len(header_content) / 1024.0
    print(f"Bundled web app into {OUTPUT_HEADER} ({size_kb:.1f} KB)")

if __name__ == '__main__':
    bundle_web_ui()
